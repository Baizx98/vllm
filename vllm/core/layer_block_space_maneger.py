class LayerBlockSpaceManager(BlockSpaceManager):
    """LayerBlockSpaceManager which manages the allocation of KV cache by layer.

    It is responsible for allocation, swapping, and allocating memory for
    tokens generated by autoregression, and currently does not support
    other advanced features such as prefix caching, and sliding window
    memory allocation but supported forking/copy-on-write.



    Args:
        BlockSpaceManager (_type_): _description_
    """

    def __init__(
        self,
        block_size: int,
        num_gpu_blocks: int,
        num_cpu_blocks: int,
        num_attn_layers: int,
        watermark: float = 0.01,
        sliding_window: Optional[int] = None,
        enable_caching: bool = False,
    ) -> None:
        self.block_size = block_size
        self.num_gpu_blocks = num_gpu_blocks
        self.num_cpu_blocks = num_cpu_blocks
        self.num_attn_layers = num_attn_layers

        # LayerBlockSpaceManager does not support prefix caching or sliding
        # window now.
        self.sliding_window = sliding_window
        self.max_block_sliding_window = None
        assert self.sliding_window is None
        self.enable_caching = enable_caching
        assert not self.enable_caching

        self.watermark = watermark
        assert 0.0 <= self.watermark <= 1.0

        self.watermark_blocks = int(watermark * num_gpu_blocks)

        # TODO CpuGpuBlockAllocator should be a new class supporting layer block
        self.block_allocator = CpuGpuBlockAllocator.create(
            allocator_type="prefix_caching" if enable_caching else "naive",
            num_gpu_blocks=num_gpu_blocks,
            num_cpu_blocks=num_cpu_blocks,
            block_size=block_size,
        )

        self.layer_block_tables: List[Dict[SeqId, BlockTable]] = [
            {} for _ in range(num_attn_layers)
        ]
        # self.layer_cross_block_tables: List[Dict[EncoderSeqId, BlockTable]] =
        # [
        #     {} for _ in range(num_attn_layers)
        # ]

        # LayerBlockSpaceManager does not support encoder model
        # self.cross_block_tables: Dict[EncoderSeqId, BlockTable] = {}

        # LayerBlockSpaceManager does not support prefix caching
        # self._computed_blocks_tracker = ComputedBlocksTracker(
        #     self.block_allocator
        # )
        # self._last_access_blocks_tracker = LastAccessBlocksTracker(
        #     self.block_allocator
